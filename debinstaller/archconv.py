"""Turns a .deb into a pacman package (.pkg.tar.xz) so Arch-based systems (Arch, CachyOS, Manjaro...) can install it and
track its files like any other package. It copies the files and their modes, nothing else.
It does NOT map Debian dependencies to Arch ones (the names differ) and does NOT run the .deb's maintainer scripts."""
import io
import lzma
import os
import re
import shutil
import subprocess
import tarfile
import time

from . import debinfo

ARCH = {"amd64": "x86_64", "arm64": "aarch64", "all": "any", "armhf": "armv7h", "i386": "i686"}
MERGED_USR = ("lib/", "lib64/", "bin/", "sbin/")  # Arch keeps these as symlinks to usr/


def pkgver(version):
    """A pacman-safe version (no hyphen, colon or tilde) plus the release number."""
    return re.sub(r"[-:~]", "_", version.split(":", 1)[-1]) + "-1"


def _dest(name):
    n = name[2:] if name.startswith("./") else name.lstrip("/")
    return "usr/" + n if n.startswith(MERGED_USR) else n


def _compress(tar_path):
    """Compresses the tar with zstd (fast; pacman reads it natively), else xz. Removes the plain tar; returns the new path."""
    if shutil.which("zstd"):
        subprocess.run(["zstd", "-T0", "-3", "-q", "-f", "--rm", tar_path], check=True)
        return tar_path + ".zst"
    with open(tar_path, "rb") as f, lzma.open(tar_path + ".xz", "wb", preset=1) as o: shutil.copyfileobj(f, o)
    os.remove(tar_path)
    return tar_path + ".xz"


def convert(info, outdir):
    """Writes <outdir>/<name>-<ver>-<arch>.pkg.tar.zst (.xz when zstd is missing) and returns (path, maintainer scripts that will not run)."""
    arch = ARCH.get(info.arch, "any")
    pkginfo = "\n".join([
        "# Generated by Deb Installer from a .deb",
        f"pkgname = {info.name}", f"pkgbase = {info.name}", f"pkgver = {pkgver(info.version)}",
        f"pkgdesc = {info.summary}", f"url = {info.fields.get('Homepage', '')}", f"builddate = {int(time.time())}",
        "packager = Deb Installer", f"size = {info.installed_size_kb * 1024}", f"arch = {arch}", ""]).encode()
    base = os.path.join(outdir, f"{info.name}-{pkgver(info.version)}-{arch}.pkg.tar")
    with debinfo.open_data_tar(info.path) as src, tarfile.open(base, mode="w", format=tarfile.PAX_FORMAT) as dst:
        ti = tarfile.TarInfo(".PKGINFO"); ti.size = len(pkginfo); ti.mtime = int(time.time()); ti.mode = 0o644
        dst.addfile(ti, io.BytesIO(pkginfo))
        for m in src.getmembers():
            dest = _dest(m.name)
            if dest in ("", "."): continue
            m.name = dest
            m.uid = m.gid = 0; m.uname = m.gname = "root"
            if m.islnk(): m.linkname = _dest(m.linkname)
            dst.addfile(m, src.extractfile(m) if m.isfile() else None)
    out = _compress(base)
    return out, debinfo.maintainer_scripts(info.path)
